public class StellDichVorV1 {
    static void main(String[] args) {
        int age = 34;
        double salary = 32.3;
        char lastLetter = 'a';
        String name = "Nadja";
        String city = "Linz";
        boolean children = true;

        System.out.println("Hallo, mein Name ist " + name + ".");
        System.out.println("Ich bin " + age + " Jahre alt und wohne derzeit in " + city + ".");
        System.out.println("Der letzte Buchstabe meines Nachnames ist " + lastLetter + ".");
        System.out.println("Ich habe kinder:" + children + ".");
        System.out.println("Nach der Ausbildung werde ich " + salary + "EURO/h verdienen.");
    }
}
